
using mvc.Repository; // Убедись, что интерфейс IRepository в этом же namespace

namespace mvc.Repository
{
    // інтерфейс визначає контракт для роботи з даними сутності Student.
    // він винесений в окремий namespace, щоб чітко відокремити шар репозиторію
    // від контролерів, моделей та контексту БД – це сприяє чистій архітектурі.
    public interface IEntityRepository<T> where T : class
    {
        // метод повертає список всіх студентів асинхронно.
        // асинхронність важлива, бо операції з БД (EF Core) можуть бути повільними,
        // і не хочеться блокувати потік під час очікування.
        Task<List<T>> GetEntityListAsync();
            
        // отримує одного студента за ідентифікатором.
        // повертає Task<Student>, бо пошук в БД теж асинхронний.
        // якщо студент не знайдений – повертається null (це обробляється в контролері).
        Task<T> GetEntityAsync(int id);

        // додає новий об'єкт Student в контекст.
        // асинхронний, бо в реалізаціях на EF Core часто використовують async-версії.
        // проте в базовому DbSet.Add є синхронна версія, тому можна було б зробити void.
        Task CreateAsync(T entity);

        // оновлює існуючий об'єкт. синхронний, бо EF Core Update працює синхронно
        // і не потребує await (всередині просто встановлюється стан Modified).

        // ЩЕ РАЗ: в Entity Framework Core немає асинхронної версії методу Update (або DbContext.Update / DbSet.Update), і це навмисне.
        // метод Update просто встановлює стан сутності в EntityState.Modified(або Added, залежно від значення ключа).
        // це т.зв. чиста in-memory операція в ChangeTracker'і EF Core - жодного I/O з базою даних не відбувається.
        // немає сенсу робити його асинхронним: він виконується миттєво і не блокує потік.
        // реально відбувається оновлення в базі тільки тоді, коли викликається SaveChanges() або SaveChangesAsync()!
        void Update(T entity);

        // видаляє студента за id. асинхронний, бо зазвичай спочатку шукаємо об'єкт
        // (FindAsync), а потім видаляємо.
        Task DeleteAsync(int id);

        // зберігає всі зміни в базі даних.
        // асинхронний SaveChangesAsync – стандарт для EF Core в веб-додатках.
        Task SaveChangesAsync();
    }
}

/*
 * навіщо взагалі цей інтерфейс?

1) відокремлення відповідальностей.
контролер не працює напряму з DbContext, а тільки через абстракцію (IRepository).
це робить контролер менш залежним від деталей роботи з БД.

2) полегшення тестування
в юніт-тестах можна легко підставити mock-реалізацію IRepository (наприклад, через Moq), яка повертатиме фіктивні дані, без запуску реальної БД.

3) гнучкість заміни реалізації
якщо завтра захочеться перейти на Dapper, Entity Framework 11, або навіть на in-memory сховище – достатньо написати нову реалізацію інтерфейсу, а контролер залишиться без змін.

4) централізоване місце для логіки доступу до даних
вся робота з EF Core захована в одному класі (наприклад, StudentRepository : IRepository), тому легше додавати логування, кешування тощо.
*/

